"""Reproduce episode 16's depth/body/scale bootstrap one explicit stage at a time.

Requires the RGB, masks and SAM3D Objects candidate generated by the other
scripts. Existing depth outputs are protected by the upstream CLI.
"""
import argparse
from pathlib import Path
import subprocess
import sys

from run_cari4d_native import runtime_env


def main():
    p = argparse.ArgumentParser()
    p.add_argument("stage", choices=["depth", "human_export", "human", "alignment", "scale"])
    p.add_argument("--episode", default="episode_000016")
    p.add_argument("--frames", type=int, default=360)
    p.add_argument("--batch-size", type=int, default=2)
    a = p.parse_args()
    root = Path(__file__).resolve().parents[1]
    source, weights, env = runtime_env(root)
    episode = root / "outputs" / a.episode
    run = episode / "cari4d" / a.episode
    depth = run / "depth/moge2"
    export = episode / "human_export" / a.episode
    init = run / "mhr_init" / (a.episode + ".pkl")
    python = sys.executable
    commands = {
        "depth": [python, source / "prep/mhr_wild_depth.py", "--video", episode / "inputs/episode_000016.0.color.mp4", "--output-depth", depth / "raw.npy", "--output-intrinsics", depth / "intrinsics.pkl", "--output-report", depth / "depth_report.json", "--device", "cuda", "--batch-size", "2", "--expected-frames", "360", "--local-files-only"],
        "human_export": [python, source / "prep/prepare_mhr_wild_export.py", "--video", episode / "inputs/episode_000016.0.color.mp4", "--mask-h5", episode / "segmentation/masks.h5", "--object-mesh", episode / "object/object_local.glb", "--intrinsics-file", depth / "intrinsics.pkl", "--output-root", export.parent],
        "human": [python, source / "prep/run_sam3d_mhr_export.py", export, "--out-file", init, "--camera-id", "0", "--depth-root", export, "--sam3d-ckpt", weights / "sam3d_body/checkpoints/sam-3d-body-dinov3/model.ckpt", "--mhr-path", weights / "sam3d_body/checkpoints/sam-3d-body-dinov3/assets/mhr_model.pt", "--chunk-size", "4", "--sam3d-cache", init.with_suffix(".sam3d.h5"), "--alignment-workers", "1", "--refit-batch-size", "128", "--human-prompt-mode", "sam2_bbox_mask", "--no-align-to-gt-depth"],
        "alignment": [python, source / "prep/align_depth_to_mhr_wild.py", export, "--raw-depth", depth / "raw.npy", "--depth-report", depth / "depth_report.json", "--mhr-init", init, "--output", depth / "aligned.h5", "--render-batch-size", "4", "--encoding-workers", "8", "--write-batch-size", "32"],
        "scale": [python, root / "scripts/calibrate_object_scale.py", "--object-dir", episode / "object", "--aligned-depth", depth / "aligned.h5", "--intrinsics", depth / "intrinsics.pkl", "--mask", episode / "segmentation/first_1_mask.png"],
    }
    # Keep historical defaults while allowing independent validation episodes.
    command = [str(x).replace("episode_000016.0.color.mp4", a.episode + ".0.color.mp4") for x in commands[a.stage]]
    if a.stage == "depth":
        command[command.index("--expected-frames") + 1] = str(a.frames)
        command[command.index("--batch-size") + 1] = str(a.batch_size)
    if a.stage == "human":
        command[command.index("--chunk-size") + 1] = str(a.batch_size)
    subprocess.run(command, cwd=source, env=env, check=True)


if __name__ == "__main__":
    main()
